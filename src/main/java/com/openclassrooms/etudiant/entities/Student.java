package com.openclassrooms.etudiant.entities;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;

/**
 * Represents a student persisted in the {@code student} table.
 */
@NoArgsConstructor
@AllArgsConstructor
@Data
@Entity
@Table(name = "student")
public class Student {
    /**
     * The ID generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;
    /**
     * The last name of the student.
     */
    @NotBlank(message = "lastName must not be blank")
    private String lastName;
    /**
     * The first name of the student.
     */
    @NotBlank(message = "firstName must not be blank")
    private String firstName;
    /**
     * The email address of the student.
     */
    @NotBlank(message = "email must not be blank")
    @Email(message = "email must be a valid email address")
    private String email;
    /**
     * The class or group to which the student belongs.
     */
    @NotBlank(message = "className must not be blank")
    private String className;
}
