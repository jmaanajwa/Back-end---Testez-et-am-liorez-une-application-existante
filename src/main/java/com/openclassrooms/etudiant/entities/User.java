package com.openclassrooms.etudiant.entities;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.validation.constraints.NotBlank;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;

import java.time.LocalDateTime;
import java.util.Collection;
import java.util.List;

/**
 * Represents a persisted user account and the information required by Spring Security.
 */
@NoArgsConstructor
@AllArgsConstructor
@Data
@Entity
@Table(name = "user")
public class User implements UserDetails {
    /**
     * The ID generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id")
    private Long id;

    /**
     * The first name of the user.
     */
    @NotBlank
    @Column(name = "firstName", nullable = false)
    private String firstName;

    /**
     * The last name of the user.
     */
    @NotBlank
    @Column(name = "lastName", nullable = false)
    private String lastName;

    /**
     * The unique account login.
     */
    @NotBlank
    @Column(name = "login", unique = true, nullable = false)
    private String login;

    /**
     * The password stored as a hash after registration.
     */
    @NotBlank
    @Column(name = "password", nullable = false)
    private String password;

    /**
     * The creation timestamp populated by Hibernate.
     */
    @CreationTimestamp
    @Column(name = "created_at")
    private LocalDateTime created_at;

    /**
     * The last modification timestamp populated by Hibernate.
     */
    @UpdateTimestamp
    @Column(name = "updated_at")
    private LocalDateTime updated_at;


    /**
     * Returns the authorities assigned to the account.
     *
     * @return an empty collection, since no roles are currently assigned
     */
    @Override
    public Collection<? extends GrantedAuthority> getAuthorities() {
        return List.of();
    }

    /**
     * Exposes the login as the Spring Security username.
     *
     * @return the account login
     */
    @Override
    public String getUsername() {
        return login;
    }

    /**
     * Indicates whether the account is considered nonexpired.
     *
     * @return always {@code true}, since account expiration is not managed
     */
    @Override
    public boolean isAccountNonExpired() {
        return true;
    }

    /**
     * Indicates whether the account is considered unlocked.
     *
     * @return always {@code true}, since account locking is not managed
     */
    @Override
    public boolean isAccountNonLocked() {
        return true;
    }

    /**
     * Indicates whether the credentials are considered nonexpired.
     *
     * @return always {@code true}, since password expiration is not managed
     */
    @Override
    public boolean isCredentialsNonExpired() {
        return true;
    }

    /**
     * Indicates whether the account is enabled.
     *
     * @return always {@code true}, since account disabling is not managed
     */
    @Override
    public boolean isEnabled() {
        return true;
    }
}
